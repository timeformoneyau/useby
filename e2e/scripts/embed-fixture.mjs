/**
 * Regenerates e2e/app/fixtureImage.ts from e2e/fixtures/label-milk.jpg.
 *
 * The fake camera needs the photo as bytes it can write to a real cache file:
 * in a release build, a `require()`d image is an Android drawable resource
 * name, not a file, and the real resize step (expo-image-manipulator) needs a
 * file. Embedding it as base64 keeps the fake camera honest — the capture
 * pipeline after the shutter runs for real on a real JPEG.
 *
 * Run after changing the fixture: node e2e/scripts/embed-fixture.mjs
 * (scripts/e2e-fixture.test.mjs fails if the two drift apart.)
 */
import { readFileSync, writeFileSync } from 'node:fs';

const jpg = readFileSync(new URL('../fixtures/label-milk.jpg', import.meta.url));
const b64 = jpg.toString('base64');
const lines = b64.match(/.{1,100}/g).map((l) => `  '${l}',`).join('\n');

writeFileSync(
  new URL('../app/fixtureImage.ts', import.meta.url),
  `// Generated by e2e/scripts/embed-fixture.mjs from e2e/fixtures/label-milk.jpg.
// Do not edit by hand. Only ever bundled into the CI flow-test build.
export const FIXTURE_JPEG_BASE64 = [
${lines}
].join('');
`,
);
console.log(`Embedded ${jpg.length} bytes.`);
